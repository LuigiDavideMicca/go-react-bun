// Command borgogen statically analyzes an app's api/ package (go/ast +
// go/types, no runtime reflection) and generates two files:
//
//   - .borgo/api-types.d.ts - route pattern -> response and request types.
//     The response type of a route is the union of the T in every
//     borgo.JSON[T] and borgo.WriteJSON call reachable from its handler
//     (helper functions in the same package are followed); the request type
//     comes from borgo.Bind[T] calls the same way. A "//borgo:type Go TS"
//     directive overrides the mapping for any named Go type.
//   - api/borgo.gen.go - mounting for handlers annotated with a
//     "//borgo:route METHOD /path" directive, so init() boilerplate is
//     optional. Manual borgo.Handle registration keeps working alongside.
package main

import (
	"fmt"
	"go/ast"
	"go/constant"
	"go/parser"
	"go/token"
	"go/types"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"golang.org/x/tools/go/packages"
)

const (
	borgoPath = "github.com/LuigiDavideMicca/borgo"
	genGoFile = "api/borgo.gen.go"
)

var (
	directiveRe = regexp.MustCompile(`^//borgo:route\s+(.+)$`)
	typeRe      = regexp.MustCompile(`^//borgo:type\s+(\S+)\s+(.+)$`)
)

type route struct {
	pattern string
	handler *types.Func
}

func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "borgogen: "+format+"\n", args...)
	os.Exit(1)
}

func main() {
	if _, err := os.Stat("api"); err != nil {
		fail("no api/ directory here; run borgogen from the app root")
	}

	// the previous generated mounting may reference deleted handlers; type
	// check against an empty stub of it instead
	genGoAbs, _ := filepath.Abs(genGoFile)
	cfg := &packages.Config{
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedSyntax |
			packages.NeedTypes | packages.NeedTypesInfo | packages.NeedDeps | packages.NeedImports,
		Overlay: map[string][]byte{genGoAbs: []byte("package " + apiPackageName() + "\n")},
	}
	pkgs, err := packages.Load(cfg, "./api")
	if err != nil {
		fail("loading api package: %v", err)
	}
	if len(pkgs) != 1 {
		fail("expected one package in api/, got %d", len(pkgs))
	}
	pkg := pkgs[0]
	for _, e := range pkg.Errors {
		fmt.Fprintln(os.Stderr, "borgogen: "+e.Error())
	}
	if len(pkg.Errors) > 0 {
		os.Exit(1)
	}

	routes := collectRoutes(pkg)
	decls := funcDecls(pkg)
	directives := collectDirectives(pkg, decls, routes)
	routes = append(routes, directives...)
	writeMounting(pkg.Name, directives, decls)

	sort.Slice(routes, func(i, j int) bool {
		a, b := strings.SplitN(routes[i].pattern, " ", 2), strings.SplitN(routes[j].pattern, " ", 2)
		if a[1] != b[1] {
			return a[1] < b[1]
		}
		return a[0] < b[0]
	})

	gen := &tsGen{
		names:     map[*types.TypeName]string{},
		taken:     map[string]bool{},
		apiPkg:    pkg.Types,
		overrides: collectTypeOverrides(pkg),
	}
	entries := make(map[string]string, len(routes))
	patterns := make([]string, 0, len(routes))
	for _, r := range routes {
		resp, req := gen.bridgeTypes(pkg, decls, decls[r.handler])
		entry := "{ response: " + resp
		if req != "" {
			entry += "; request: " + req
		}
		entries[r.pattern] = entry + " }"
		patterns = append(patterns, r.pattern)
	}

	var out strings.Builder
	out.WriteString("// generated by borgogen - do not edit\n\n")
	for _, def := range gen.defs {
		out.WriteString(def)
		out.WriteString("\n")
	}
	out.WriteString("declare module \"borgo\" {\n  interface ApiRoutes {\n")
	for _, p := range patterns {
		fmt.Fprintf(&out, "    %q: %s;\n", p, entries[p])
	}
	out.WriteString("  }\n}\n\nexport {};\n")

	if err := os.MkdirAll(".borgo", 0o755); err != nil {
		fail("%v", err)
	}
	writeIfChanged(filepath.Join(".borgo", "api-types.d.ts"), out.String())
	fmt.Printf("borgogen: %d routes -> .borgo/api-types.d.ts\n", len(patterns))
}

// apiPackageName reads the package clause of the first real api/*.go file so
// the overlay stub and the generated mounting use the right name.
func apiPackageName() string {
	entries, err := os.ReadDir("api")
	if err != nil {
		fail("%v", err)
	}
	fset := token.NewFileSet()
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".go") || e.Name() == "borgo.gen.go" {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join("api", e.Name()), nil, parser.PackageClauseOnly)
		if err == nil {
			return f.Name.Name
		}
	}
	return "api"
}

var handlerSig = "func(http.ResponseWriter, *http.Request)"

func isHandlerSig(fn *types.Func) bool {
	sig, ok := fn.Type().(*types.Signature)
	if !ok || sig.Params().Len() != 2 || sig.Results().Len() != 0 {
		return false
	}
	return sig.Params().At(0).Type().String() == "net/http.ResponseWriter" &&
		sig.Params().At(1).Type().String() == "*net/http.Request"
}

// collectDirectives finds every //borgo:route directive and validates it
// against the manually registered patterns.
func collectDirectives(pkg *packages.Package, decls map[*types.Func]*ast.FuncDecl, manual []route) []route {
	taken := map[string]string{}
	for _, r := range manual {
		name := "?"
		if r.handler != nil {
			name = r.handler.Name()
		}
		taken[r.pattern] = name + " (borgo.Handle)"
	}

	var out []route
	for fn, decl := range decls {
		if decl.Doc == nil {
			continue
		}
		for _, comment := range decl.Doc.List {
			m := directiveRe.FindStringSubmatch(comment.Text)
			if m == nil {
				continue
			}
			pattern := strings.TrimSpace(m[1])
			pos := pkg.Fset.Position(comment.Pos())
			if !isHandlerSig(fn) {
				fail("%s: //borgo:route on %s, which is not a %s", pos, fn.Name(), handlerSig)
			}
			if prev, dup := taken[pattern]; dup {
				fail("%s: pattern %q already registered by %s", pos, pattern, prev)
			}
			taken[pattern] = fn.Name() + " (//borgo:route)"
			out = append(out, route{pattern: pattern, handler: fn})
		}
	}
	return out
}

// writeMounting generates api/borgo.gen.go registering every directive
// handler, or removes it when no directives exist.
func writeMounting(pkgName string, directives []route, decls map[*types.Func]*ast.FuncDecl) {
	if len(directives) == 0 {
		os.Remove(genGoFile)
		return
	}
	sorted := append([]route(nil), directives...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].pattern < sorted[j].pattern })

	var out strings.Builder
	out.WriteString("// generated by borgogen - do not edit\npackage " + pkgName + "\n\n")
	out.WriteString("import \"" + borgoPath + "\"\n\nfunc init() {\n")
	for _, r := range sorted {
		fmt.Fprintf(&out, "\tborgo.Handle(%q, %s)\n", r.pattern, r.handler.Name())
	}
	out.WriteString("}\n")
	writeIfChanged(genGoFile, out.String())
}

func writeIfChanged(path, content string) {
	if current, err := os.ReadFile(path); err == nil && string(current) == content {
		return
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		fail("%v", err)
	}
}

// borgoFunc resolves a call expression's callee to a function of the borgo
// package, returning its name, or "" when it is anything else.
func borgoFunc(info *types.Info, call *ast.CallExpr) (string, *ast.Ident) {
	fun := call.Fun
	if idx, ok := fun.(*ast.IndexExpr); ok {
		// explicit type arguments, e.g. borgo.Bind[T](r)
		fun = idx.X
	}
	sel, ok := fun.(*ast.SelectorExpr)
	if !ok {
		return "", nil
	}
	fn, ok := info.Uses[sel.Sel].(*types.Func)
	if !ok || fn.Pkg() == nil || fn.Pkg().Path() != borgoPath {
		return "", nil
	}
	return fn.Name(), sel.Sel
}

func collectRoutes(pkg *packages.Package) []route {
	var routes []route
	for _, file := range pkg.Syntax {
		ast.Inspect(file, func(n ast.Node) bool {
			call, ok := n.(*ast.CallExpr)
			if !ok {
				return true
			}
			name, _ := borgoFunc(pkg.TypesInfo, call)
			if name != "Handle" || len(call.Args) != 2 {
				return true
			}
			tv := pkg.TypesInfo.Types[call.Args[0]]
			if tv.Value == nil || tv.Value.Kind() != constant.String {
				return true
			}
			routes = append(routes, route{
				pattern: constant.StringVal(tv.Value),
				handler: handlerFunc(pkg.TypesInfo, call.Args[1]),
			})
			return true
		})
	}
	return routes
}

func handlerFunc(info *types.Info, expr ast.Expr) *types.Func {
	switch e := expr.(type) {
	case *ast.Ident:
		if fn, ok := info.Uses[e].(*types.Func); ok {
			return fn
		}
	case *ast.SelectorExpr:
		if fn, ok := info.Uses[e.Sel].(*types.Func); ok {
			return fn
		}
	}
	return nil
}

func funcDecls(pkg *packages.Package) map[*types.Func]*ast.FuncDecl {
	decls := map[*types.Func]*ast.FuncDecl{}
	for _, file := range pkg.Syntax {
		for _, d := range file.Decls {
			if fd, ok := d.(*ast.FuncDecl); ok {
				if fn, ok := pkg.TypesInfo.Defs[fd.Name].(*types.Func); ok {
					decls[fn] = fd
				}
			}
		}
	}
	return decls
}

type tsGen struct {
	names     map[*types.TypeName]string
	taken     map[string]bool
	defs      []string
	apiPkg    *types.Package
	overrides map[string]string
}

// collectTypeOverrides gathers every "//borgo:type Go TS" directive. The Go
// type is "pkgpath.Name" for imported types or a bare name for api types.
func collectTypeOverrides(pkg *packages.Package) map[string]string {
	out := map[string]string{}
	for _, file := range pkg.Syntax {
		for _, group := range file.Comments {
			for _, comment := range group.List {
				m := typeRe.FindStringSubmatch(comment.Text)
				if m == nil {
					if strings.HasPrefix(comment.Text, "//borgo:type") {
						pos := pkg.Fset.Position(comment.Pos())
						fail("%s: malformed directive, want //borgo:type <go type> <ts type>", pos)
					}
					continue
				}
				out[m[1]] = strings.TrimSpace(m[2])
			}
		}
	}
	return out
}

type union struct {
	seen  map[string]bool
	parts []string
}

func (u *union) add(ts string) {
	if u.seen == nil {
		u.seen = map[string]bool{}
	}
	if !u.seen[ts] {
		u.seen[ts] = true
		u.parts = append(u.parts, ts)
	}
}

func (u *union) String() string {
	return strings.Join(u.parts, " | ")
}

// localCallee resolves a call to a function of the api package itself, so
// borgo.JSON/WriteJSON/Bind calls inside helpers are followed.
func localCallee(pkg *packages.Package, call *ast.CallExpr) *types.Func {
	var fn *types.Func
	switch e := call.Fun.(type) {
	case *ast.Ident:
		fn, _ = pkg.TypesInfo.Uses[e].(*types.Func)
	case *ast.SelectorExpr:
		fn, _ = pkg.TypesInfo.Uses[e.Sel].(*types.Func)
	}
	if fn == nil || fn.Pkg() != pkg.Types {
		return nil
	}
	return fn
}

// bridgeTypes unions the response type (borgo.JSON[T] and borgo.WriteJSON
// calls) and the request type (borgo.Bind[T] calls) reachable from the
// handler, following calls into same-package helper functions.
func (g *tsGen) bridgeTypes(pkg *packages.Package, decls map[*types.Func]*ast.FuncDecl, decl *ast.FuncDecl) (response, request string) {
	var resp, req union
	visited := map[*ast.FuncDecl]bool{}

	var walk func(d *ast.FuncDecl)
	walk = func(d *ast.FuncDecl) {
		if d == nil || d.Body == nil || visited[d] {
			return
		}
		visited[d] = true
		ast.Inspect(d.Body, func(n ast.Node) bool {
			call, ok := n.(*ast.CallExpr)
			if !ok {
				return true
			}
			switch name, sel := borgoFunc(pkg.TypesInfo, call); name {
			case "JSON", "Bind":
				if inst, ok := pkg.TypesInfo.Instances[sel]; ok && inst.TypeArgs.Len() == 1 {
					ts := g.tsType(inst.TypeArgs.At(0))
					if name == "JSON" {
						resp.add(ts)
					} else {
						req.add(ts)
					}
				}
			case "WriteJSON":
				if len(call.Args) == 3 {
					if tv := pkg.TypesInfo.Types[call.Args[2]]; tv.Type != nil {
						resp.add(g.tsType(types.Default(tv.Type)))
					}
				}
			case "":
				if fn := localCallee(pkg, call); fn != nil {
					walk(decls[fn])
				}
			}
			return true
		})
	}
	walk(decl)

	if len(resp.parts) == 0 {
		return "unknown", req.String()
	}
	return resp.String(), req.String()
}

func hasCustomMarshal(t types.Type) bool {
	for _, T := range []types.Type{t, types.NewPointer(t)} {
		if m, _, _ := types.LookupFieldOrMethod(T, true, nil, "MarshalJSON"); m != nil {
			return true
		}
	}
	return false
}

func (g *tsGen) tsType(t types.Type) string {
	switch t := t.(type) {
	case *types.Named:
		obj := t.Obj()
		if ts, ok := g.override(obj); ok {
			return ts
		}
		if obj.Pkg() != nil && obj.Pkg().Path() == "time" && obj.Name() == "Time" {
			return "string"
		}
		if hasCustomMarshal(t) {
			return "unknown"
		}
		if s, ok := t.Underlying().(*types.Struct); ok {
			return g.interfaceFor(obj, s)
		}
		return g.tsType(t.Underlying())
	case *types.Alias:
		return g.tsType(types.Unalias(t))
	case *types.Basic:
		switch {
		case t.Info()&types.IsBoolean != 0:
			return "boolean"
		case t.Info()&types.IsNumeric != 0:
			return "number"
		case t.Info()&types.IsString != 0:
			return "string"
		}
		return "unknown"
	case *types.Pointer:
		return g.tsType(t.Elem()) + " | null"
	case *types.Slice:
		if b, ok := t.Elem().(*types.Basic); ok && b.Kind() == types.Byte {
			return "string"
		}
		return "Array<" + g.tsType(t.Elem()) + ">"
	case *types.Array:
		return "Array<" + g.tsType(t.Elem()) + ">"
	case *types.Map:
		if b, ok := t.Key().Underlying().(*types.Basic); ok && b.Info()&(types.IsString|types.IsNumeric) != 0 {
			return "Record<string, " + g.tsType(t.Elem()) + ">"
		}
		return "unknown"
	case *types.Struct:
		return "{ " + strings.Join(g.fields(t), "; ") + " }"
	}
	return "unknown"
}

func (g *tsGen) override(obj *types.TypeName) (string, bool) {
	if obj.Pkg() != nil {
		if ts, ok := g.overrides[obj.Pkg().Path()+"."+obj.Name()]; ok {
			return ts, true
		}
	}
	if obj.Pkg() == nil || obj.Pkg() == g.apiPkg {
		if ts, ok := g.overrides[obj.Name()]; ok {
			return ts, true
		}
	}
	return "", false
}

func (g *tsGen) interfaceFor(obj *types.TypeName, s *types.Struct) string {
	if name, ok := g.names[obj]; ok {
		return name
	}
	name := obj.Name()
	if g.taken[name] && obj.Pkg() != nil {
		pkgName := obj.Pkg().Name()
		name = strings.ToUpper(pkgName[:1]) + pkgName[1:] + name
	}
	for i := 2; g.taken[name]; i++ {
		name = fmt.Sprintf("%s%d", obj.Name(), i)
	}
	g.taken[name] = true
	g.names[obj] = name

	fields := g.fields(s)
	g.defs = append(g.defs, "export interface "+name+" {\n  "+strings.Join(fields, ";\n  ")+";\n}\n")
	return name
}

// fields follows encoding/json: exported fields only, json tags for naming,
// omitempty marks the field optional, embedded structs are flattened.
func (g *tsGen) fields(s *types.Struct) []string {
	var out []string
	for i := 0; i < s.NumFields(); i++ {
		f := s.Field(i)
		if !f.Exported() {
			continue
		}
		name, opts := parseJSONTag(s.Tag(i))
		if name == "-" {
			continue
		}
		if f.Embedded() && name == "" {
			et := f.Type()
			if p, ok := et.(*types.Pointer); ok {
				et = p.Elem()
			}
			if named, ok := et.(*types.Named); ok && !hasCustomMarshal(named) {
				if es, ok := named.Underlying().(*types.Struct); ok {
					out = append(out, g.fields(es)...)
					continue
				}
			}
		}
		if name == "" {
			name = f.Name()
		}
		optional := ""
		if strings.Contains(opts, "omitempty") {
			optional = "?"
		}
		ts := g.tsType(f.Type())
		if strings.Contains(opts, "string") && ts == "number" {
			ts = "string"
		}
		out = append(out, fmt.Sprintf("%s%s: %s", name, optional, ts))
	}
	if len(out) == 0 {
		return []string{"[key: string]: unknown"}
	}
	return out
}

func parseJSONTag(tag string) (name, opts string) {
	value, ok := lookupTag(tag, "json")
	if !ok {
		return "", ""
	}
	if i := strings.Index(value, ","); i >= 0 {
		return value[:i], value[i+1:]
	}
	return value, ""
}

func lookupTag(tag, key string) (string, bool) {
	// minimal reflect.StructTag.Lookup
	for tag != "" {
		i := 0
		for i < len(tag) && tag[i] == ' ' {
			i++
		}
		tag = tag[i:]
		if tag == "" {
			break
		}
		i = 0
		for i < len(tag) && tag[i] > ' ' && tag[i] != ':' && tag[i] != '"' {
			i++
		}
		if i == 0 || i+1 >= len(tag) || tag[i] != ':' || tag[i+1] != '"' {
			break
		}
		k := tag[:i]
		tag = tag[i+1:]
		i = 1
		for i < len(tag) && tag[i] != '"' {
			if tag[i] == '\\' {
				i++
			}
			i++
		}
		if i >= len(tag) {
			break
		}
		value := tag[1:i]
		tag = tag[i+1:]
		if k == key {
			return value, true
		}
	}
	return "", false
}
